import { useMutation, useQuery } from "@tanstack/react-query"
import { motion } from "framer-motion"
import { ArrowLeft, Download, FileSpreadsheet, Lightbulb, Loader2 } from "lucide-react"
import { Link, useParams } from "react-router"
import { toast } from "sonner"

import { ApiError } from "@/api/client"
import { categoriesApi, expenseKeys } from "@/api/expenses"
import { reportKeys, reportsApi } from "@/api/reports"
import type { Report } from "@/api/types"
import { CategoryIcon } from "@/components/CategoryIcon"
import { MoneyText } from "@/components/MoneyText"
import { Button } from "@/components/ui/button"
import { Skeleton } from "@/components/ui/skeleton"
import { NotFoundPage } from "@/features/shell/NotFoundPage"
import { useSplit } from "@/features/splits/useSplit"
import { firstName, formatDay, formatPeriod, formatShortDate, plural, timeAgo } from "@/lib/format"
import { formatMoney } from "@/lib/money"

import { CategoryDonut, DailyTrend, MemberBars, MemberCategoryHeatmap, WeekdayBars } from "./ReportCharts"

const container = { hidden: {}, show: { transition: { staggerChildren: 0.07 } } }
const item = { hidden: { opacity: 0, y: 14 }, show: { opacity: 1, y: 0, transition: { duration: 0.35, ease: [0.22, 1, 0.36, 1] as const } } }

/** /app/splits/:splitId/reports/:reportId */
export function ReportPage() {
  const { splitId = "", reportId = "" } = useParams()
  const report = useQuery({ queryKey: reportKeys.detail(reportId), queryFn: () => reportsApi.get(reportId), retry: false })
  const split = useSplit(splitId)

  if (report.isError && report.error instanceof ApiError && report.error.status === 404) {
    return <NotFoundPage title="Report not found" message="This report doesn't exist, or you're not a member of its split." />
  }
  if (report.isPending || !report.data) {
    return (
      <div className="space-y-6" aria-busy="true">
        <Skeleton className="h-40 rounded-[28px]" />
        <div className="grid gap-4 sm:grid-cols-3">
          {Array.from({ length: 3 }, (_, i) => (
            <Skeleton key={i} className="h-28 rounded-3xl" />
          ))}
        </div>
        <Skeleton className="h-72 rounded-3xl" />
      </div>
    )
  }
  return <ReportView report={report.data} splitName={split.data?.name ?? "Split"} splitEmoji={split.data?.emoji ?? "🏠"} />
}

function ReportView({ report, splitName, splitEmoji }: { report: Report; splitName: string; splitEmoji: string }) {
  const { stats, currency } = report
  const period = formatPeriod(report.periodStart, report.periodEnd) ?? `${formatShortDate(report.periodStart)} – ${formatShortDate(report.periodEnd)}`

  const pdf = useMutation({ mutationFn: () => reportsApi.downloadPdf(report), onSuccess: () => toast.success("PDF downloaded") })
  const csv = useMutation({ mutationFn: () => reportsApi.exportCsv(report.splitId), onSuccess: () => toast.success("CSV downloaded") })

  return (
    <motion.div initial="hidden" animate="show" variants={container} className="space-y-6">
      <motion.div variants={item}>
        <Link to={`/app/splits/${report.splitId}?tab=reports`} className="inline-flex items-center gap-1.5 text-sm text-muted-foreground transition-colors hover:text-foreground">
          <ArrowLeft className="size-4" /> {splitName}
        </Link>
      </motion.div>

      {/* Header + hero number */}
      <motion.header variants={item} className="relative overflow-hidden rounded-[28px] border border-hairline bg-surface p-6 sm:p-8">
        <div className="glow-radial pointer-events-none absolute -right-24 -top-32 size-[420px]" />
        <div className="relative flex flex-wrap items-start justify-between gap-4">
          <div>
            <p className="font-mono text-xs uppercase tracking-[0.2em] text-muted-foreground">
              {splitEmoji} Spending report · {period}
            </p>
            <h1 className="mt-3 font-heading text-[clamp(1.5rem,4vw,2.25rem)] font-bold leading-tight">{splitName}</h1>
            <p className="mt-1 text-sm text-muted-foreground">
              Generated by {firstName(report.generatedByName)} {timeAgo(report.generatedAt)}
            </p>
          </div>
          <div className="flex flex-wrap gap-2">
            <Button size="xl" onClick={() => pdf.mutate()} disabled={pdf.isPending}>
              {pdf.isPending ? <Loader2 className="animate-spin" /> : <Download />} Download PDF
            </Button>
            <Button size="xl" variant="outline" onClick={() => csv.mutate()} disabled={csv.isPending}>
              {csv.isPending ? <Loader2 className="animate-spin" /> : <FileSpreadsheet />} Export CSV
            </Button>
          </div>
        </div>
        <div className="relative mt-8 flex flex-wrap items-end gap-x-10 gap-y-4">
          <div>
            <p className="text-sm text-muted-foreground">Total spend</p>
            <MoneyText minor={stats.totalSpendMinor} currency={currency} className="block text-[clamp(3rem,9vw,4.5rem)] font-bold leading-none tracking-tighter" />
          </div>
        </div>
      </motion.header>

      {/* KPI cards */}
      <motion.div variants={item} className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <Kpi label="Expenses" value={String(stats.expenseCount)} hint={`${formatMoney(stats.avgPerExpenseMinor, currency)} on average`} />
        <Kpi label="Average per day" value={formatMoney(stats.avgPerDayMinor, currency)} hint={`over ${plural(stats.days, "day")}`} />
        <Kpi label="Average per person" value={formatMoney(stats.avgPerPersonMinor, currency)} hint={`${plural(stats.byMember.length, "person", "people")}`} />
        <Kpi label="Biggest expense" value={stats.topExpenses[0] ? formatMoney(stats.topExpenses[0].amountMinor, currency) : "–"} hint={stats.topExpenses[0]?.description ?? ""} />
      </motion.div>

      {/* Insights */}
      {report.insights.length > 0 && (
        <motion.section variants={item} aria-labelledby="insights-heading">
          <h2 id="insights-heading" className="mb-3 font-heading text-xl font-bold">
            What stands out
          </h2>
          <div className="grid gap-3 md:grid-cols-2">
            {report.insights.map((text, i) => (
              <motion.div key={text} variants={item} className="flex gap-3 rounded-2xl border border-hairline bg-surface p-4" style={{ borderLeftColor: "var(--lime-ink)", borderLeftWidth: 3 }}>
                <Lightbulb className="mt-0.5 size-4 shrink-0 text-lime-ink" aria-hidden />
                <p className="text-[15px] leading-snug">
                  <span className="sr-only">Insight {i + 1}: </span>
                  {text}
                </p>
              </motion.div>
            ))}
          </div>
        </motion.section>
      )}

      {/* Charts */}
      <motion.div variants={item} className="grid gap-6 lg:grid-cols-2">
        <CategoryDonut stats={stats} currency={currency} />
        <MemberBars members={stats.byMember} currency={currency} />
      </motion.div>
      <motion.div variants={item}>
        <DailyTrend stats={stats} currency={currency} />
      </motion.div>
      <motion.div variants={item} className="grid gap-6 lg:grid-cols-[minmax(0,1fr)_minmax(0,1fr)]">
        <WeekdayBars stats={stats} currency={currency} />
        <TopExpenses report={report} />
      </motion.div>
      <motion.div variants={item}>
        <MemberCategoryHeatmap stats={stats} currency={currency} />
      </motion.div>
    </motion.div>
  )
}

function Kpi({ label, value, hint }: { label: string; value: string; hint: string }) {
  return (
    <div className="rounded-3xl border border-hairline bg-surface p-5">
      <p className="text-sm text-muted-foreground">{label}</p>
      <p className="mt-1 font-money text-2xl font-semibold">{value}</p>
      <p className="mt-0.5 truncate text-xs text-muted-foreground">{hint}</p>
    </div>
  )
}

function TopExpenses({ report }: { report: Report }) {
  const { stats, currency } = report
  const max = stats.topExpenses[0]?.amountMinor ?? 1
  const categories = useQuery({ queryKey: expenseKeys.categories(report.splitId), queryFn: () => categoriesApi.list(report.splitId), staleTime: 5 * 60_000 })
  const byName = new Map((categories.data ?? []).map((c) => [c.name, c]))
  return (
    <section className="rounded-3xl border border-hairline bg-surface p-5 sm:p-6" aria-labelledby="top-heading">
      <h3 id="top-heading" className="font-heading text-lg font-bold">
        Biggest expenses
      </h3>
      <p className="mt-0.5 text-sm text-muted-foreground">The five that cost the most</p>
      <ol className="mt-4 space-y-3">
        {stats.topExpenses.map((e, i) => (
          <li key={e.expenseId} className="flex items-center gap-3">
            <span className="w-4 font-money text-xs text-muted-foreground">{i + 1}</span>
            <CategoryIcon size="sm" category={e.categoryName ? byName.get(e.categoryName) : undefined} />
            <div className="min-w-0 flex-1">
              <div className="flex items-baseline justify-between gap-3">
                <p className="truncate text-sm font-medium">{e.description}</p>
                <MoneyText minor={e.amountMinor} currency={currency} animateValue={false} className="text-sm font-semibold" />
              </div>
              <div className="mt-1 h-1.5 overflow-hidden rounded-full bg-surface-2" aria-hidden>
                <div className="h-full rounded-full" style={{ width: `${Math.max(4, (e.amountMinor / max) * 100)}%`, backgroundColor: "var(--viz-1)" }} />
              </div>
              <p className="mt-1 text-xs text-muted-foreground">
                {e.paidByName ? `${firstName(e.paidByName)} paid` : "Paid"} · {formatDay(e.date)}
                {e.categoryName && ` · ${e.categoryName}`}
              </p>
            </div>
          </li>
        ))}
      </ol>
    </section>
  )
}
